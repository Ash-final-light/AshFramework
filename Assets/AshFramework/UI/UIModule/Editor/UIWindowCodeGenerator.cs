using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;

namespace AshFramework.UI.UIModule.Editor
{
    [Serializable]
    public sealed class UIWindowGenerationOptions
    {
        public string WindowName = "Inventory";
        public string Namespace = "Game.UI.Inventory";
        public string ScriptDirectory = "Assets/GameScripts/UI/Inventory";
        public string PrefabPath = "Assets/Resources/UI/Inventory.prefab";
        public UILayer Layer = UILayer.Main;
    }

    public sealed class UIWindowGenerationResult
    {
        public readonly List<string> Written = new List<string>();
        public readonly List<string> Preserved = new List<string>();
    }

    public static class UIWindowCodeGenerator
    {
        private const string Marker = "// <auto-generated by AshFramework.UI.UIModule>";
        private static readonly Regex Identifier = new Regex("^[A-Za-z_][A-Za-z0-9_]*$", RegexOptions.CultureInvariant);
        private static readonly HashSet<string> Keywords = new HashSet<string>(StringComparer.Ordinal)
        {
            "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked",
            "class", "const", "continue", "decimal", "default", "delegate", "do", "double", "else",
            "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for", "foreach",
            "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock", "long",
            "namespace", "new", "null", "object", "operator", "out", "override", "params", "private",
            "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof",
            "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try",
            "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void",
            "volatile", "while"
        };

        public static string GetValidationError(UIWindowGenerationOptions options)
        {
            if (options == null || !IsIdentifier(options.WindowName))
            {
                return "窗口名必须是有效 C# 标识符，例如 Inventory；不需要 Window 后缀。";
            }

            if (string.IsNullOrWhiteSpace(options.Namespace))
            {
                return "命名空间不能为空。";
            }

            foreach (string segment in options.Namespace.Split('.'))
            {
                if (!IsIdentifier(segment))
                {
                    return "命名空间包含无效标识符。";
                }
            }

            try
            {
                ResolveAssetsPath(options.ScriptDirectory);
                string prefab = ResolveAssetsPath(options.PrefabPath);

                if (!string.Equals(Path.GetExtension(prefab), ".prefab", StringComparison.OrdinalIgnoreCase))
                {
                    return "Prefab 路径必须以 .prefab 结尾。";
                }

                if (!Enum.IsDefined(typeof(UILayer), options.Layer))
                {
                    return "无效 UI 层级。";
                }

                GetResourceKey(options.PrefabPath);
            }
            catch (Exception exception) when (exception is ArgumentException || exception is IOException ||
                exception is NotSupportedException || exception is UnauthorizedAccessException)
            {
                return exception.Message;
            }

            return null;
        }

        public static UIWindowGenerationResult Generate(UIWindowGenerationOptions options)
        {
            string error = GetValidationError(options);

            if (error != null)
            {
                throw new ArgumentException(error, nameof(options));
            }

            string directory = ResolveAssetsPath(options.ScriptDirectory);
            Dictionary<string, string> templates = BuildTemplates(options);
            string generatedPath = Path.Combine(directory, "Generated", options.WindowName + "WindowBase.g.cs");

            // Preflight all destinations before any file is written.
            foreach (KeyValuePair<string, string> template in templates)
            {
                string path = Path.Combine(directory, template.Key);

                if (Directory.Exists(path))
                {
                    throw new IOException("生成目标被同名目录占用：" + path);
                }

                EnsureNoReparsePoints(path);
            }

            if (File.Exists(generatedPath))
            {
                string existing = File.ReadAllText(generatedPath).Replace("\r\n", "\n");
                string expectedHeader = Marker + "\n// Owner: " + options.Namespace + "." + options.WindowName + "\n";

                if (!existing.StartsWith(expectedHeader, StringComparison.Ordinal))
                {
                    throw new IOException("拒绝覆盖生成器标记或命名空间/窗口身份不匹配的文件：" + generatedPath);
                }
            }

            var result = new UIWindowGenerationResult();
            var backups = new Dictionary<string, byte[]>();

            try
            {
                foreach (KeyValuePair<string, string> template in templates)
                {
                    string path = Path.Combine(directory, template.Key);

                    if (File.Exists(path) && path != generatedPath)
                    {
                        result.Preserved.Add(ToAssetPath(path));
                        continue;
                    }

                    backups.Add(path, File.Exists(path) ? File.ReadAllBytes(path) : null);
                    Directory.CreateDirectory(Path.GetDirectoryName(path));
                    File.WriteAllText(path, template.Value.Replace("\r\n", "\n"), new UTF8Encoding(false));
                    result.Written.Add(ToAssetPath(path));
                }
            }
            catch
            {
                foreach (KeyValuePair<string, byte[]> backup in backups)
                {
                    if (backup.Value == null)
                    {
                        File.Delete(backup.Key);
                    }
                    else
                    {
                        File.WriteAllBytes(backup.Key, backup.Value);
                    }
                }

                throw;
            }

            return result;
        }

        public static IReadOnlyDictionary<string, string> Preview(UIWindowGenerationOptions options)
        {
            string error = GetValidationError(options);

            if (error != null)
            {
                throw new ArgumentException(error, nameof(options));
            }

            return BuildTemplates(options);
        }

        public static string GetResourceKey(string prefabPath)
        {
            if (string.IsNullOrWhiteSpace(prefabPath) || !prefabPath.EndsWith(".prefab", StringComparison.OrdinalIgnoreCase))
            {
                throw new ArgumentException("Prefab 路径必须以 .prefab 结尾。 ", nameof(prefabPath));
            }

            string normalized = prefabPath.Replace('\\', '/');
            int index = normalized.IndexOf("/Resources/", StringComparison.Ordinal);

            if (index < 0 || normalized.IndexOf("/Resources/", index + 1, StringComparison.Ordinal) >= 0)
            {
                throw new ArgumentException("默认 Resources 加载器要求 Prefab 位于唯一的 Resources 目录下。可选择其他 Resources 目录。 ");
            }

            string key = normalized.Substring(index + "/Resources/".Length);
            key = key.Substring(0, key.Length - ".prefab".Length);

            if (string.IsNullOrWhiteSpace(key))
            {
                throw new ArgumentException("Prefab 资源地址不能为空。 ");
            }

            return key;
        }

        private static bool IsIdentifier(string value)
        {
            return value != null && Identifier.IsMatch(value) && !Keywords.Contains(value);
        }

        private static string ResolveAssetsPath(string relativePath)
        {
            if (string.IsNullOrWhiteSpace(relativePath))
            {
                throw new ArgumentException("输出路径不能为空。 ");
            }

            string normalized = relativePath.Replace('\\', '/');

            if (!normalized.StartsWith("Assets/", StringComparison.Ordinal) ||
                normalized.Contains("/../") || normalized.Contains("/./") || normalized.EndsWith("/..", StringComparison.Ordinal) ||
                normalized.IndexOfAny(new[] { '"', '\r', '\n', '\0', ':', '*', '?', '<', '>', '|' }) >= 0)
            {
                throw new ArgumentException("输出路径必须是 Assets 下的普通相对路径，不能包含路径跳转。 ");
            }

            string assetsRoot = Path.GetFullPath(UnityEngine.Application.dataPath);
            string absolute = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(assetsRoot), normalized));

            if (!absolute.StartsWith(assetsRoot + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
            {
                throw new ArgumentException("输出目标超出 Assets。 ");
            }

            EnsureNoReparsePoints(absolute);
            return absolute;
        }

        private static void EnsureNoReparsePoints(string path)
        {
            string assets = Path.GetFullPath(UnityEngine.Application.dataPath);
            string current = path;

            while (current != null && current.StartsWith(assets, StringComparison.OrdinalIgnoreCase))
            {
                if ((File.Exists(current) || Directory.Exists(current)) &&
                    (File.GetAttributes(current) & FileAttributes.ReparsePoint) != 0)
                {
                    throw new IOException("输出路径不能经过符号链接或目录联接：" + current);
                }

                current = Path.GetDirectoryName(current);
            }
        }

        private static string ToAssetPath(string absolute)
        {
            string project = Path.GetDirectoryName(UnityEngine.Application.dataPath);
            return absolute.Substring(project.Length + 1).Replace('\\', '/');
        }

        private static Dictionary<string, string> BuildTemplates(UIWindowGenerationOptions options)
        {
            string name = options.WindowName;
            string ns = options.Namespace;
            string key = GetResourceKey(options.PrefabPath).Replace("\\", "\\\\").Replace("\"", "\\\"");
            string baseCode = $@"{Marker}
// Owner: {ns}.{name}
using System;
using AshFramework.UI.UIModule;

namespace {ns}
{{
    public abstract class {name}WindowBase : UIWindow<{name}Args>
    {{
        public static readonly UIKey<{name}Args> Key = new UIKey<{name}Args>(""{ns}.{name}"");
        protected {name}View View {{ get; private set; }}

        public static void Register(UIRegistry registry, Func<{name}Window> factory)
        {{
            registry.Register(Key, new UIDefinition(""{key}"", UILayer.{options.Layer}), factory);
        }}

        protected sealed override void OnCreate(UIView view)
        {{
            View = RequireView<{name}View>(view);
            OnInitialize();
        }}

        protected virtual void OnInitialize()
        {{
        }}

        protected sealed override void OnRelease()
        {{
            try
            {{
                OnDispose();
            }}
            finally
            {{
                View = null;
            }}
        }}

        protected virtual void OnDispose()
        {{
        }}
    }}
}}
";
            string windowCode = $@"using AshFramework.UI.UIModule;

namespace {ns}
{{
    public sealed class {name}Window : {name}WindowBase
    {{
        protected override void OnInitialize()
        {{
            // Bind control events once here. Unbind them in OnDispose.
        }}

        protected override void OnBind({name}Args args)
        {{
            View.Render(args);
        }}

        protected override void OnShow()
        {{
            // Start subscriptions needed only while visible.
        }}

        protected override void OnHide()
        {{
            // Stop visible subscriptions; Context.VisibleToken is already cancelled.
        }}

        protected override void OnDispose()
        {{
            // Clean up partial initialization too. View can be null if type validation failed.
        }}
    }}
}}
";
            string argsCode = $@"namespace {ns}
{{
    public sealed class {name}Args
    {{
        // Add immutable display parameters here.
    }}
}}
";
            string viewCode = $@"using AshFramework.UI.UIModule;
using UnityEngine;

namespace {ns}
{{
    [DisallowMultipleComponent]
    public sealed class {name}View : UIView
    {{
        // Add serialized control references and local view events here.
        public void Render({name}Args args)
        {{
        }}
    }}
}}
";
            return new Dictionary<string, string>
            {
                { Path.Combine("Generated", name + "WindowBase.g.cs"), baseCode },
                { name + "Window.cs", windowCode },
                { name + "Args.cs", argsCode },
                { name + "View.cs", viewCode }
            };
        }
    }
}
